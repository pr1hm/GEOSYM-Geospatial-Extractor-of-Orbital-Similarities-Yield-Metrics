def make_5km_bbox(lat: float, lon: float) -> List[float]:
    """Generates a 5x5 km bounding box [min_lon, min_lat, max_lon, max_lat] centered at (lat, lon)."""
    delta_lat = 2.5 / 111.0  # ~0.0225 degrees
    cos_lat = max(0.15, math.cos(math.radians(lat)))
    delta_lon = 2.5 / (111.0 * cos_lat)
    return [
        round(lon - delta_lon, 5),
        round(lat - delta_lat, 5),
        round(lon + delta_lon, 5),
        round(lat + delta_lat, 5)
    ]

