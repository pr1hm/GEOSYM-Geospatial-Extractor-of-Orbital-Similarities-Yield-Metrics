# Auto-compute 5x5 km bounding box and STAC preview URLs for all Earth sites
def get_all_earth_sites() -> List[Dict[str, Any]]:
    sites = []
    for site in KNOWN_NASA_ANALOGS + UNRECOGNIZED_ANALOG_CANDIDATES:
        site_copy = dict(site)
        site_copy["target_system"] = "Earth"
        site_copy["bbox_5km"] = make_5km_bbox(site_copy["latitude"], site_copy["longitude"])
        if "satellite_preview_url" not in site_copy or not site_copy["satellite_preview_url"]:
            # Provide high-reliability Planetary Computer DEM / S2 preview template
            lat_int = int(abs(site_copy["latitude"]))
            lat_dir = "N" if site_copy["latitude"] >= 0 else "S"
            lon_int = int(abs(site_copy["longitude"]))
            lon_dir = "E" if site_copy["longitude"] >= 0 else "W"
            item_name = f"Copernicus_DSM_COG_10_{lat_dir}{lat_int:02d}_00_{lon_dir}{lon_int:03d}_00_DEM"
            site_copy["satellite_preview_url"] = (
                f"https://planetarycomputer.microsoft.com/api/data/v1/item/preview.png?"
                f"collection=cop-dem-glo-30&item={item_name}"
            )
        sites.append(site_copy)
    return sites

